const glyphs = new Map<string, Uint8Array>();
for (const [ch, rows] of Object.entries(G)) {
  const bits = new Uint8Array(35);
  rows.split(' ').forEach((r, y) => { for (let x = 0; x < 5; x++) bits[y * 5 + x] = r[x] === '1' ? 1 : 0; });
  glyphs.set(ch, bits);
}

export function normalizeLed(text: string): string {
  return text
    .normalize('NFD').replace(/[̀-ͯ]/g, '')
    .replace(/[“”„]/g, '"').replace(/[‘’`´]/g, "'").replace(/[–—]/g, '-')
    .toUpperCase();
}

export function glyph(ch: string): Uint8Array {
  return glyphs.get(ch) ?? glyphs.get('?')!;
}

